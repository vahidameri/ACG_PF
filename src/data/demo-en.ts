export function translateDemo<T>(db: T): T {
  const tr = (v: string) => (EN[v] ? EN[v] : v.includes('\n') ? v.split('\n').map((l) => EN[l] ?? l).join('\n') : v)
  const out = {} as Record<string, unknown[]>
  for (const [k, rows] of Object.entries(db as Record<string, Record<string, unknown>[]>)) {
    out[k] = rows.map((r) => {
      const o: Record<string, unknown> = {}
      for (const [f, v] of Object.entries(r)) o[f] = typeof v === 'string' && /[؀-ۿ]/.test(v) ? tr(v) : v
      return o
    })
  }
  return out as T
}
